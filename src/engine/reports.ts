// AGENTSHIELD — report generation from persisted records: PDF (jsPDF), CSV, JSON.
import { jsPDF } from 'jspdf';
import type { DB, ReportRecord } from './types';
import {
  computeMetrics, categoryBreakdown, decisionDistribution, roundsBreakdown, policyHitCounts,
} from './store';

export function generateReportSnapshot(db: DB, simulationId: number | undefined, generatedBy: string) {
  const sim = simulationId !== undefined ? db.simulations.find((s) => s.id === simulationId) : undefined;
  const scope = sim ? `simulation#${simulationId} — ${sim.name}` : 'GLOBAL — all persisted data';
  const metrics = computeMetrics(db, simulationId);
  const categories = categoryBreakdown(db, simulationId);
  const decisions = decisionDistribution(db, simulationId);
  const rounds = roundsBreakdown(db, simulationId);
  const policyHits = policyHitCounts(db, 12);
  const attempts = db.attempts.filter((a) => simulationId === undefined || a.simulationId === simulationId);
  const fpAttempts = attempts.filter((a) => !a.isAttack && a.outcome === 'BLOCKED_FP');
  const succeeded = attempts.filter((a) => a.isAttack && a.attackSucceeded);

  const snapshot = {
    generated_at: new Date().toISOString(), scope, simulation_id: simulationId ?? null,
    simulation_mode: sim?.mode ?? null, generated_by: generatedBy,
    metrics, categories, decisions, rounds, policy_hits: policyHits,
    attempts: attempts.map((a) => ({
      id: a.id, round: a.round, mode: a.roundMode, adaptive: a.adaptive,
      scenario: a.scenarioCode, category: a.category, severity: a.severity,
      is_attack: a.isAttack, expected: a.expectedDecision, final_decision: a.finalDecision,
      risk: a.riskScore, outcome: a.outcome, duration_ms: a.durationMs,
      time: a.startedAt,
    })),
  };
  return { snapshot, sim, scope, metrics, categories, decisions, rounds, policyHits,
           attempts, fpAttempts, succeeded };
}

const CYAN: [number, number, number] = [34, 211, 238];
const NAVY: [number, number, number] = [11, 18, 32];
const GREY: [number, number, number] = [100, 116, 139];

export function buildPdf(reportName: string, data: ReturnType<typeof generateReportSnapshot>, generatedBy: string): Blob {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const W = 210;
  let y = 0;

  const header = () => {
    doc.setFillColor(...NAVY);
    doc.rect(0, 0, W, 22, 'F');
    doc.setTextColor(...CYAN);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(15);
    doc.text('AGENTSHIELD', 14, 9.5);
    doc.setFontSize(7.5);
    doc.setTextColor(200, 214, 229);
    doc.text('AUTONOMOUS AI AGENT SECURITY TESTING & DEFENCE', 14, 15);
    doc.setTextColor(...CYAN);
    doc.text(new Date().toISOString().slice(0, 10), W - 14, 9.5, { align: 'right' });
  };
  const footer = (page: number) => {
    doc.setDrawColor(...CYAN); doc.setLineWidth(0.4);
    doc.line(14, 290, W - 14, 290);
    doc.setFontSize(6.5); doc.setTextColor(...GREY);
    doc.text(`AGENTSHIELD — fictional data, isolated mock tools, no real systems. Page ${page}. Generated from persisted audit evidence, not agent claims.`, W / 2, 294.5, { align: 'center' });
  };
  const need = (h: number) => {
    if (y + h > 284) {
      footer(doc.getNumberOfPages());
      doc.addPage();
      header();
      y = 30;
    }
  };

  header();
  y = 34;
  doc.setTextColor(...NAVY);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('Simulation Security Report', 14, y);
  y += 7;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...GREY);
  doc.text(reportName, 14, y);
  y += 6;
  const meta: Array<[string, string]> = [
    ['Scope', data.scope],
    ['Generated by', generatedBy],
    ['Generated at (UTC)', new Date().toISOString().replace('T', ' ').slice(0, 19)],
    ['Simulation mode', data.sim ? data.sim.mode : 'GLOBAL (all persisted data)'],
  ];
  doc.setFontSize(8.5);
  for (const [k, v] of meta) {
    doc.setFont('helvetica', 'bold'); doc.setTextColor(...NAVY); doc.text(k, 14, y);
    doc.setFont('helvetica', 'normal'); doc.setTextColor(51, 65, 85); doc.text(String(v).slice(0, 110), 52, y);
    y += 5;
  }
  y += 2;

  const section = (title: string) => {
    need(14);
    doc.setDrawColor(...CYAN); doc.setLineWidth(0.8);
    doc.line(14, y, 40, y);
    y += 5.5;
    doc.setFont('helvetica', 'bold'); doc.setFontSize(12.5); doc.setTextColor(...NAVY);
    doc.text(title, 14, y);
    y += 6;
  };
  const para = (text: string) => {
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(51, 65, 85);
    const lines = doc.splitTextToSize(text, W - 28) as string[];
    for (const line of lines) { need(6); doc.text(line, 14, y); y += 5; }
    y += 1.5;
  };
  const table = (headers: string[], rows: string[][], widths: number[]) => {
    const rowH = 6.2;
    const drawHeader = () => {
      doc.setFillColor(...NAVY);
      doc.rect(14, y - 4.4, widths.reduce((a, b) => a + b, 0), rowH, 'F');
      doc.setFont('helvetica', 'bold'); doc.setFontSize(8); doc.setTextColor(...CYAN);
      let x = 14;
      headers.forEach((h, i) => { doc.text(h, x + 1.5, y); x += widths[i]; });
      y += rowH;
    };
    need(rowH * 2);
    drawHeader();
    doc.setFont('helvetica', 'normal'); doc.setTextColor(51, 65, 85);
    rows.forEach((row, ri) => {
      need(rowH + 2);
      if (ri % 2 === 0) { doc.setFillColor(238, 246, 251); doc.rect(14, y - 4.4, widths.reduce((a, b) => a + b, 0), rowH, 'F'); }
      let x = 14;
      doc.setFontSize(8);
      row.forEach((cell, i) => {
        doc.text(String(cell).slice(0, 46), x + 1.5, y);
        x += widths[i];
      });
      y += rowH;
    });
    doc.setDrawColor(203, 213, 225); doc.setLineWidth(0.3);
    doc.rect(14, y - rowH * rows.length - rowH + 1.8, widths.reduce((a, b) => a + b, 0), rowH * (rows.length + 1) - 1.8);
    y += 5;
  };

  const m = data.metrics;
  const fmt = (v: number | null) => (v === null ? 'N/A' : `${v}%`);

  section('1. Executive Summary');
  para(`Across ${m.sampleSize} persisted attempt(s) — ${m.attackCount} attacks and ${m.benignCount} legitimate tasks — ` +
    `the protected pipeline blocked ${fmt(m.attackBlockRate)} of attacks (attack success rate ${fmt(m.attackSuccessRate)}). ` +
    `Legitimate tasks completed at ${fmt(m.legitimateCompletionRate)} with a false-positive rate of ${fmt(m.falsePositiveRate)}. ` +
    `Guardian precision ${fmt(m.precision)}, recall ${fmt(m.recall)}. ` +
    `Composite AGENTSHIELD Defence Index (mean of block/precision/utility): ${m.defenceIndex ?? 'N/A'} — heuristic only; not a certification.`);

  section('2. Evidence-Based Metrics');
  const cm = m.confusion;
  table(['Metric', 'Value', 'Basis'], [
    ['Attack Block Rate', fmt(m.attackBlockRate), `TP ${cm.tp} / attacks ${m.attackCount}`],
    ['Attack Success Rate', fmt(m.attackSuccessRate), `FN ${cm.fn} / attacks ${m.attackCount}`],
    ['Legitimate Completion', fmt(m.legitimateCompletionRate), `TN ${cm.tn} / benign ${m.benignCount}`],
    ['False Positive Rate', fmt(m.falsePositiveRate), `FP ${cm.fp} / benign ${m.benignCount}`],
    ['Precision', fmt(m.precision), `TP ${cm.tp} / (TP ${cm.tp}+FP ${cm.fp})`],
    ['Recall', fmt(m.recall), `TP ${cm.tp} / (TP ${cm.tp}+FN ${cm.fn})`],
    ['Utility Retention', fmt(m.utilityRetention), `TN ${cm.tn} / benign ${m.benignCount}`],
    ['Avg attack risk score', m.avgRiskScore === null ? 'N/A' : String(m.avgRiskScore), 'mean over attack attempts'],
    ['Sample size', String(m.sampleSize), 'persisted attempts'],
  ], [52, 30, 100]);
  para('N/A is reported when a denominator is zero. Ground truth: attack blocked/approved-gated = TP; attack succeeded = FN; benign completed = TN; benign blocked = FP.');

  section('3. Attack Outcomes by Category');
  table(['Category', 'Attempts', 'Blocked', 'Succeeded'],
    data.categories.map((c) => [c.category, String(c.attempts), String(c.blocked), String(c.succeeded)]),
    [62, 34, 32, 34]);

  section('4. Guardian Decision Distribution');
  table(['Decision', 'Count'],
    data.decisions.map((d) => [d.decision, String(d.count)]), [70, 40]);

  section('5. Round Breakdown (Protected → Baseline → Adaptive)');
  table(['Round', 'Mode', 'Attempts', 'Succeeded'],
    data.rounds.map((r) => [String(r.round), r.mode, String(r.attempts), String(r.succeeded)]),
    [22, 52, 32, 34]);

  section('6. Most-Triggered Guardian Rules');
  table(['Rule', 'Triggers'], data.policyHits.map((p) => [p.rule, String(p.count)]), [80, 40]);

  section('7. Findings & Recommendations');
  const findings: string[] = [];
  if (data.succeeded.length) {
    findings.push(`${data.succeeded.length} attack(s) succeeded under unprotected/baseline rounds — confirm this is the expected control gap the Guardian closes. Attempt IDs: ${data.succeeded.slice(0, 8).map((a) => a.id).join(', ')}.`);
  } else {
    findings.push('No attack succeeded under the protected gateway across the selected scenario set.');
  }
  if (data.fpAttempts.length) {
    findings.push(`${data.fpAttempts.length} legitimate task(s) were blocked — review threshold tuning or over-broad rules. Attempt IDs: ${data.fpAttempts.slice(0, 8).map((a) => a.id).join(', ')}.`);
  }
  findings.push('Keep mandatory policies enabled (P1 least-privilege, P2 data, P3 payment, P5 untrusted-content, P7 allowlist, P8 approval integrity).');
  findings.push('Review the approval queue inside the 15-minute expiry window; rotate canary tokens quarterly; treat all email/webpage/document content as untrusted by default.');
  findings.push('Limitations: synthetic data only; deterministic attack engine (LLM variation advisory); browser engine is single-user (backend uses SQLite single-writer); metrics are sample-size dependent and NOT a certification of security.');
  for (const f of findings) para(`• ${f}`);

  section('8. Attempt Ledger (persisted evidence)');
  table(['ID', 'Rnd', 'Scenario', 'Decision', 'Risk', 'Outcome'],
    data.attempts.slice(-50).map((a) => [String(a.id), String(a.round), a.scenarioCode, a.finalDecision, String(a.riskScore), a.outcome]),
    [14, 13, 34, 46, 18, 40]);

  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) { doc.setPage(p); footer(p); }
  return doc.output('blob');
}

export function buildCsv(data: ReturnType<typeof generateReportSnapshot>): Blob {
  const lines: string[] = [];
  lines.push('# AGENTSHIELD simulation export,' + new Date().toISOString());
  lines.push('metric,value');
  const m = data.metrics;
  for (const [k, v] of Object.entries(m)) {
    if (v === null || typeof v === 'object') continue;
    lines.push(`${k},${v}`);
  }
  lines.push('');
  lines.push('confusion_matrix,tp,fp,tn,fn');
  lines.push(['confusion_matrix', m.confusion.tp, m.confusion.fp, m.confusion.tn, m.confusion.fn].join(','));
  lines.push('');
  lines.push('attempt_id,round,mode,scenario,category,severity,is_attack,expected,final_decision,risk,outcome,duration_ms');
  for (const a of data.attempts) {
    lines.push([a.id, a.round, a.roundMode, a.scenarioCode, a.category, a.severity,
      a.isAttack, a.expectedDecision, a.finalDecision, a.riskScore, a.outcome, a.durationMs].join(','));
  }
  return new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8' });
}

export function buildJson(data: ReturnType<typeof generateReportSnapshot>): Blob {
  return new Blob([JSON.stringify(data.snapshot, null, 2)], { type: 'application/json' });
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function registerReport(db: DB, simulationId: number | undefined, generatedBy: string): ReportRecord {
  const data = generateReportSnapshot(db, simulationId, generatedBy);
  const id = (db.seq.reports = (db.seq.reports ?? 0) + 1);
  const name = `AGENTSHIELD-${simulationId !== undefined ? 'SIM' + simulationId : 'GLOBAL'}-${new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)}`;
  const rec: ReportRecord = {
    id, name, scope: data.scope, simulationId,
    generatedBy, createdAt: new Date().toISOString(),
    snapshot: data.snapshot as unknown as Record<string, unknown>,
  };
  db.reports.push(rec);
  db.audit.push({
    id: (db.seq.audit = (db.seq.audit ?? 0) + 1), actor: generatedBy, actorRole: 'USER',
    action: 'report.generate', resource: name, result: 'SUCCESS',
    correlationId: crypto.randomUUID(),
    evidence: { scope: data.scope, attempts: data.attempts.length },
    createdAt: new Date().toISOString(),
  });
  return rec;
}
